// shared/app/port/SettingsStorage.kt —— 设置持久化端口
//
// ★ 只抽「读一份设置 / 写一份设置」，不抽存储介质：
//   桌面端写 `%APPDATA%\PhotoMgm\settings.json`（用户能直接看/改/备份），
//   安卓端写独立 SharedPreferences。两者的失败策略都是「读失败回落默认值、写失败不抛」——
//   这条策略属于**实现**，不属于业务，所以端口上只有两个朴素的方法。
//
// ★ 为什么把这条策略交给实现而不是共享层统一兜住：
//   共享层若替实现 catch 异常，会把「磁盘满 / 只读盘」这类平台信号吞成一个静默的默认值，
//   实现方再想区分就来不及了。端口保持朴素，各实现自己决定怎么降级。
//
// ★ `load()` 必须返回**已清洗过**的设置（非法枚举名、越界模板值等一律回落默认），
//   否则坏配置文件会让共享层收到一个业务上不存在的取值。
package app.port

import app.api.Settings

/** 设置持久化（平台实现由装配根注入）。 */
interface SettingsStorage {
    /** 读取设置；无配置文件或内容损坏时返回默认值，**不抛异常**。 */
    fun load(): Settings

    /** 保存设置（原子写：先写临时位置再改名，避免掉电留下半个文件）。失败不抛异常。 */
    fun save(settings: Settings)
}
